const MARKS: Record<string, string> = {
  slack: SLACK_MARK,
  discord: DISCORD_MARK,
  telegram: TELEGRAM_MARK
};

/** The mark for a messenger id, or nothing. */
export function messengerMark(id: string): HTMLElement | undefined {
  const svg = MARKS[id];
  if (!svg) return undefined;
  const wrap = el('span', 'bmwrap');
  wrap.innerHTML = svg;
  return wrap;
}
