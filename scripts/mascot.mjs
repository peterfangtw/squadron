// Bakes the mascot's frames into src/ui/mascot_frames.ts from the approved
// design source. The chick stays editable as shapes in docs/mockups/lib/
// chick.mjs; the bundle carries only the grid each shape list rasterizes to,
// as run-length tone strings, so the webview paints it without the shape code.
//
//   node scripts/mascot.mjs           write the file
//   node scripts/mascot.mjs --check   exit 1 if the file differs from a fresh bake
//
// The check is what src/test/board/mascot_frames.test.ts runs: a hand edit, or a
// chick.mjs change nobody re-baked, goes red in the gate.

import { readFileSync, writeFileSync } from 'node:fs';
import * as prettier from 'prettier';
import { frames } from '../docs/mockups/lib/chick.mjs';

const SOURCE = 'docs/mockups/lib/chick.mjs';
const OUTPUT = 'src/ui/mascot_frames.ts';

// pixel.mjs's tone letters, in its header's order. '.' is an empty cell.
const TONES = 'WVGDOEQITYPKH';

/**
 * One frame as runs over the flattened grid: a tone letter, then how many
 * cells it covers. A run never crosses a row end, so each run is one
 * `fillRect` and the decoder needs no row splitting.
 */
function encode(grid) {
  const size = grid.length;
  let out = '';
  for (const row of grid) {
    if (row.length !== size) throw new Error(`a ${size}-row frame has a ${row.length}-cell row`);
    for (let x = 0; x < size;) {
      const tone = row[x];
      if (tone !== '.' && !TONES.includes(tone)) throw new Error(`unknown tone ${tone}`);
      let end = x;
      while (end + 1 < size && row[end + 1] === tone) end++;
      out += tone + (end - x + 1);
      x = end + 1;
    }
  }
  return out;
}

const names = Object.keys(frames);
const size = frames[names[0]].length;
const body = `// Generated by scripts/mascot.mjs from ${SOURCE}. Do not hand-edit — re-run
// \`npm run mascot\`.

/** Width and height of every frame, in sprite pixels. */
export const SIZE = ${size};

/** The tones a frame uses, one letter each; \`.\` is an empty cell. */
export const TONES = '${TONES}';

export type FrameName = ${names.map((n) => `'${n}'`).join(' | ')};

/** Every frame, in strip order: a tone letter then its cell count, row-major,
 *  no run crossing a row end. */
export const FRAMES: Readonly<Record<FrameName, string>> = {
${names.map((n) => `  ${n}: '${encode(frames[n])}'`).join(',\n')}
};
`;

const config = (await prettier.resolveConfig(OUTPUT)) ?? {};
const formatted = await prettier.format(body, { ...config, filepath: OUTPUT });

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    // Absent reads as stale.
  }
  if (current !== formatted) {
    console.error(`${OUTPUT} is not what ${SOURCE} bakes to. Run \`npm run mascot\`.`);
    process.exit(1);
  }
  console.log(`${OUTPUT} is current.`);
} else {
  writeFileSync(OUTPUT, formatted);
  console.log(`${OUTPUT} (${formatted.length} bytes)`);
}
