// Bakes the shipped icons and documentation wordmarks from the approved
// Squadron vectors. Geometry stays in the design sources; this generator only
// supplies the colour and intrinsic size each destination needs.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const ICON_SOURCE = 'docs/mockups/squadron-wordmark/eclipse.svg';
const WORDMARK_SOURCE = 'docs/mockups/squadron-wordmark/wordmark-michroma-semibold.svg';

const eclipse = readFileSync(ICON_SOURCE, 'utf8').trim();
const wordmark = readFileSync(WORDMARK_SOURCE, 'utf8').trim();

function coloured(svg, ink, size) {
  if (!svg.startsWith('<svg ') || !svg.includes('fill="currentColor"')) {
    throw new Error('approved Squadron SVG no longer has the expected currentColor root');
  }
  const dimensions = size ? `width="${size}" height="${size}" ` : '';
  return svg.replace('<svg ', `<svg ${dimensions}color="${ink}" `);
}

const GENERATED = (source, purpose) => `<!-- ${purpose}

     Generated by scripts/icons.mjs from ${source}. Do not hand-edit — re-run
     \`npm run icons\`. -->`;

// Command icons are image URIs, so they cannot inherit the surrounding host
// colour. Separate black and white files keep the Eclipse legible in both
// themes while preserving its approved 128-unit geometry at the host's 16px.
for (const [theme, ink] of [
  ['dark', '#FFFFFF'],
  ['light', '#000000']
]) {
  const output = `media/icon-editor-${theme}.svg`;
  const header = GENERATED(ICON_SOURCE, 'The Squadron Eclipse mark for IDE chrome.');
  writeFileSync(output, `${header}\n${coloured(eclipse, ink, 150)}\n`);
  console.log(output);
}

// The panel's watermarks. The webview's CSP admits images from data: alone and
// media/*.svg does not ship, so both marks ride the bundle as data URIs. A
// background image cannot inherit currentColor, so the ink is baked: mid grey
// reads on every theme preset, dark or light. Opacity on the root rather than
// fill-opacity, which would double-paint where the letters' stroke meets fill.
const WATERMARK = (svg) =>
  'data:image/svg+xml,' +
  encodeURIComponent(coloured(svg, '#808080').replace('<svg ', '<svg opacity=".07" '));
const marks = `// Generated by scripts/icons.mjs from ${WORDMARK_SOURCE} and
// ${ICON_SOURCE}. Do not hand-edit — re-run \`npm run icons\`.

export const WORDMARK_URI = '${WATERMARK(wordmark)}';

export const ECLIPSE_URI = '${WATERMARK(eclipse)}';
`;
writeFileSync('src/ui/marks.ts', marks);
console.log('src/ui/marks.ts');

// The Marketplace and every theme choose the surrounding surface, and the
// package icon has no plate of its own. Each colour holds 3:1 on both #181818
// and white at the shape's edge; the pale belts sit inside the limb.
// Baked at 2x, so a high-density list does not stair-step the belts.
bake('media/icon.png', 256, 256, '', painted(eclipse));

// The README's title. vsce refuses an SVG in a README, so it is a PNG, and the
// galleries pick the page colour — light Marketplace, dark Open VSX, the
// editor's own theme — so the ink is a blue that reads on both.
// Baked at 3x the width the README draws it.
const INK = '#1564B2';
bake('media/squadron-wordmark.png', 1200, 150, `color:${INK}`, withPaintedEclipse(wordmark));

// The same two marks as vectors for use outside the extension — slides, sites,
// social cards. Not in package.json's `files`, so they do not ship.
for (const [output, source, purpose, svg] of [
  [
    'media/squadron-icon.svg',
    ICON_SOURCE,
    'The painted Squadron Eclipse, as media/icon.png.',
    painted(eclipse)
  ],
  [
    'media/squadron-wordmark.svg',
    WORDMARK_SOURCE,
    'The Squadron wordmark in one ink.',
    coloured(wordmark, INK)
  ],
  [
    'media/squadron-wordmark-painted.svg',
    WORDMARK_SOURCE,
    'The Squadron wordmark with the painted Eclipse as its O, as media/squadron-wordmark.png.',
    coloured(withPaintedEclipse(wordmark), INK)
  ],
  // Neutral letters so the painted O carries the colour. Named for the
  // background, as media/icon-editor-*.svg are.
  ...[
    ['dark', '#FFFFFF'],
    ['light', '#000000']
  ].map(([theme, ink]) => [
    `media/squadron-wordmark-painted-${theme}.svg`,
    WORDMARK_SOURCE,
    `The Squadron wordmark with the painted Eclipse as its O, for ${theme} backgrounds.`,
    coloured(withPaintedEclipse(wordmark), ink)
  ])
]) {
  writeFileSync(output, `${GENERATED(source, purpose)}\n${svg}\n`);
  console.log(output);
}

// The wordmark's O is ICON_SOURCE's drawing in a scaled group, so the painted
// icon drops into that group whole; the letters keep currentColor.
function withPaintedEclipse(svg) {
  const slot =
    /<g transform="([^"]+)"><defs><mask .*?<\/g><path d="[^"]+" ?\/>(?:<circle [^>]+\/>){3}<\/g>/.exec(
      svg
    );
  if (!slot) throw new Error('approved wordmark no longer has its Eclipse group');
  const inner = painted(eclipse)
    .replace(/^<svg [^>]*>/, '')
    .replace(/<\/svg>$/, '');
  return svg.replace(slot[0], `<g transform="${slot[1]}" fill="none">${inner}</g>`);
}

// Jupiter's belts in a brown-to-gold ring with three orange moons. Paint only:
// the geometry stays in ICON_SOURCE.
function painted(svg) {
  const RIBBON = ['#A0662C', '#BC8618'];
  const BELTS = ['#EFE3CC', '#C98B5A', '#F0E2C4', '#B5623A'];
  const LIMB = '#A85A2E';
  const MOON = '#C9781E';
  const [ribbonX1, ribbonY1, ribbonX2, ribbonY2] = [14, 90, 115, 38];
  const found = /<circle cx="64\.00" cy="64\.00" r="([\d.]+)"\/>/.exec(svg);
  if (!found) throw new Error('approved Eclipse no longer has its sphere');
  const [sphere, radiusText] = found;
  const radius = Number(radiusText);
  const belts = BELTS.flatMap((colour, i) =>
    [i, i + 1].map((edge) => `<stop offset="${edge / BELTS.length}" stop-color="${colour}"/>`)
  ).join('');
  // Square to the ribbon, so the belts lie parallel to it. The axis stops at
  // r/3, just short of where the ribbon cuts the sphere, so the last belt runs
  // on to that cut and no pale band lands on the sphere's straight edge.
  const ribbonLength = Math.hypot(ribbonX2 - ribbonX1, ribbonY2 - ribbonY1);
  const acrossX = (ribbonY1 - ribbonY2) / ribbonLength;
  const acrossY = (ribbonX2 - ribbonX1) / ribbonLength;
  const beltAxis = `x1="${64 - acrossX * radius}" y1="${64 - acrossY * radius}" x2="${64 + (acrossX * radius) / 3}" y2="${64 + (acrossY * radius) / 3}"`;
  const defs =
    `<linearGradient id="orbit" gradientUnits="userSpaceOnUse" x1="${ribbonX1}" y1="${ribbonY1}" x2="${ribbonX2}" y2="${ribbonY2}"><stop stop-color="${RIBBON[0]}"/><stop offset="1" stop-color="${RIBBON[1]}"/></linearGradient>` +
    `<linearGradient id="belts" gradientUnits="userSpaceOnUse" ${beltAxis}>${belts}</linearGradient>` +
    `<radialGradient id="limb" gradientUnits="userSpaceOnUse" cx="64" cy="64" r="${radius}"><stop offset=".62" stop-color="${LIMB}" stop-opacity="0"/><stop offset="1" stop-color="${LIMB}"/></radialGradient>`;
  const filled = (fill) => sphere.replace('/>', ` fill="url(#${fill})"/>`);
  return [
    ['fill="currentColor"', 'fill="none"'],
    ['<defs>', `<defs>${defs}`],
    [' mask="url(#eclipse-back)"/>', ' mask="url(#eclipse-back)" fill="url(#orbit)"/>'],
    [sphere, filled('belts') + filled('limb')],
    ['<path d="M112.78', '<path fill="url(#orbit)" d="M112.78'],
    ['<circle cx="8.10"', `<circle fill="${MOON}" cx="8.10"`],
    ['<circle cx="78.54"', `<circle fill="${MOON}" cx="78.54"`],
    ['<circle cx="110.00"', `<circle fill="${MOON}" cx="110.00"`]
  ].reduce((painting, [from, to]) => {
    if (!painting.includes(from)) throw new Error(`approved Eclipse no longer has ${from}`);
    return painting.replace(from, to);
  }, svg);
}

function bake(output, width, height, style, svg) {
  const chrome = process.env.SQUADRON_CHROME;
  if (!chrome) {
    console.log(`${output} skipped — set SQUADRON_CHROME to a headless browser to bake it`);
    return;
  }
  const file = join(mkdtempSync(join(tmpdir(), 'squadron-icons-')), 'page.html');
  writeFileSync(
    file,
    `<body style="margin:0;${style}">` +
      `<style>svg{display:block;width:${width}px;height:${height}px}</style>${svg}</body>`
  );
  execFileSync(chrome, [
    '--headless',
    '--disable-gpu',
    `--screenshot=${output}`,
    `--window-size=${width},${height}`,
    '--default-background-color=00000000',
    '--virtual-time-budget=1200',
    pathToFileURL(file).href
  ]);
  console.log(output);
}
